#!/usr/bin/env python3
"""Generate pc-port/src/asset_manifest.h from a reference asset folder.

    python3 tools/gen_manifest.py [ASSETS_DIR] [OUT_HEADER]

Defaults: pc-port/bin/windows/assets -> pc-port/src/asset_manifest.h.

The manifest lists every file the PC port reads from assets/ (name, size, CRC-32) and
how the extractor (pc-port/src/extract.c) produces it from the player's own disc image:
  AM_ISO   copied from the data track's ISO9660 file system (same name),
  AM_LZ    X.dec.bin = X.PPB of the data track, word-LZ decompressed (lz.c),
  AM_CDDA  TRACKnn.WAV = CD-DA track nn, 44.1 kHz 16-bit stereo (as tools/rip_cdda.py).
CD-DA files are optional (the game runs without music). Standard library only.
"""
import os
import re
import sys
import zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def crc32_file(path):
    crc = 0
    with open(path, "rb") as f:
        while True:
            b = f.read(1 << 20)
            if not b:
                return crc & 0xFFFFFFFF
            crc = zlib.crc32(b, crc)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "pc-port", "bin", "windows", "assets")
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, "pc-port", "src", "asset_manifest.h")
    names = sorted(n for n in os.listdir(src) if os.path.isfile(os.path.join(src, n)))
    rows, total = [], 0
    for n in names:
        if len(n) > 31:
            raise SystemExit("name too long: " + n)
        size = os.path.getsize(os.path.join(src, n))
        crc = crc32_file(os.path.join(src, n))
        m = re.fullmatch(r"TRACK(\d\d)\.WAV", n, re.I)
        if m:
            kind, track, opt, isoname = "AM_CDDA", int(m.group(1)), 1, None
        elif n.endswith(".dec.bin"):
            kind, track, opt, isoname = "AM_LZ", 0, 0, n[:-len(".dec.bin")] + ".PPB"
        else:
            kind, track, opt, isoname = "AM_ISO", 0, 0, n
        rows.append((n, isoname, kind, track, opt, size, crc))
        total += size
    lines = [
        "/* Generated by tools/gen_manifest.py from the reference assets (%d files) - do not edit. */" % len(rows),
        "#ifndef ASSET_MANIFEST_H",
        "#define ASSET_MANIFEST_H",
        "#include <stdint.h>",
        "",
        "enum { AM_ISO = 0, AM_LZ = 1, AM_CDDA = 2 };",
        "",
        "typedef struct {",
        "    const char *name;      /* file name in assets/ */",
        "    const char *src;       /* ISO9660 source file (AM_ISO / AM_LZ), NULL for AM_CDDA */",
        "    uint8_t     kind;      /* AM_* */",
        "    uint8_t     track;     /* AM_CDDA: CD track number */",
        "    uint8_t     optional;  /* 1 = the game runs without it (music) */",
        "    uint32_t    size;",
        "    uint32_t    crc32;",
        "} AssetManifestEntry;",
        "",
        "#define ASSET_MANIFEST_COUNT %d" % len(rows),
        "#define ASSET_MANIFEST_TOTAL %dull   /* bytes */" % total,
        "",
        "static const AssetManifestEntry g_assetManifest[ASSET_MANIFEST_COUNT] = {",
    ]
    for n, isoname, kind, track, opt, size, crc in rows:
        s = '"%s"' % isoname if isoname else "NULL"
        lines.append('    { %-20s %-16s %-8s %d, %d, %9du, 0x%08Xu },' % ('"%s",' % n, s + ",", kind + ",", track, opt, size, crc))
    lines += ["};", "", "#endif", ""]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("%s: %d files, %d bytes" % (out, len(rows), total))


if __name__ == "__main__":
    main()
