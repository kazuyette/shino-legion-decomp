enum { IT_LIVES, IT_REFILL, IT_INF_HP, IT_SHUR, IT_INF_SHUR, IT_NINJ, IT_CLEAR, IT_GOTO, IT_CLOSE, IT_COUNT };

static int s_open, s_sel, s_gotoIdx, s_infHp, s_infShur, s_mute;
static char s_msg[40];
static int  s_msgT;

static int in_stage(void)
{
    return Res_OverlayResident() == OVL_SHINOBI && R16(A_GAME_MODE) == 6;
}

static void msg(const char *m) { snprintf(s_msg, sizeof s_msg, "%s", m); s_msgT = 120; }

int DebugMenu_IsOpen(void) { return s_open; }

void DebugMenu_SetInfinite(int energy, int shurikens) { s_infHp = energy; s_infShur = shurikens; }

int DebugMenu_ClearStage(void)
{
    if (!in_stage() || (R16(A_STAGE_ST) & 7)) return 0;
    W16(A_STAGE_ST, (R16(A_STAGE_ST) & 0xFFF8u) | 10u);   /* same request as a boss death */
    return 1;
}

void DebugMenu_GotoStage(int idx)
{
    if (idx < 0 || idx > 17) return;
    if (Res_OverlayResident() == OVL_SHINOBI && R16(A_GAME_MODE) >= 5 && R16(A_GAME_MODE) <= 7) {
        W16(A_STAGE_IDX, (uint32_t)idx);                    /* keep lives / score */
        W16(A_STAGE_ST, 0);
        W16(A_CHECKPT, 0); W16(A_RESPAWN, 0);
        W16(A_GAME_MODE, 0);                                /* 0x0606B5EE -> 3 -> 4 -> 5 load */
    } else {
        Boot_DevStartStage(idx);                            /* from the title / DIRECTOR */
    }
}

static void stage_name(int idx, char *b) { snprintf(b, 16, "%d-%d", (idx / 2 + 1) % 100, (idx % 2 + 1) % 10); }

static void activate(int dir)    /* dir: 0 = A/Enter, -1/+1 = left/right */
{
    int st = in_stage();
    switch (s_sel) {
    case IT_LIVES:
        if (dir) { int v = RS16(A_LIVES) + dir; if (v < 0) v = 0; if (v > 99) v = 99; W16(A_LIVES, (uint32_t)v); }
        break;
    case IT_REFILL:
        if (!dir) { if (st) { W16(A_HP, R16(A_HP_MAX)); msg("ENERGIE AU MAX"); } else msg("PAS EN JEU"); }
        break;
    case IT_INF_HP:   s_infHp ^= 1; break;
    case IT_SHUR: {
        int v = RS16(A_SHURIKENS) + (dir ? 10 * dir : 10);
        if (v < 0) v = 0;
        if (v > 999) v = 999;
        W16(A_SHURIKENS, (uint32_t)v);
        break;
    }
    case IT_INF_SHUR: s_infShur ^= 1; break;
    case IT_NINJ:     W16(A_NINJUTSU, R16(A_NINJUTSU) ? 0 : 1); break;
    case IT_CLEAR:
        if (!dir) {
            if (DebugMenu_ClearStage()) { msg("STAGE CLEAR"); s_open = 0; s_mute = 15; }
            else msg("PAS EN JEU");
        }
        break;
    case IT_GOTO:
        if (dir) s_gotoIdx = (s_gotoIdx + dir + 18) % 18;
        else { DebugMenu_GotoStage(s_gotoIdx); s_open = 0; s_mute = 15; }
        break;
    case IT_CLOSE:
        if (!dir) { s_open = 0; s_mute = 15; }
        break;
    }
}

static void toggle(void)
{
    s_open = !s_open;
    if (s_open) { int i = RS16(A_STAGE_IDX); s_gotoIdx = (i >= 0 && i <= 17) ? i : 0; }
    else s_mute = 15;
}

void DebugMenu_HandleEvent(const SDL_Event *ev)
{
    int key = -1;   /* 0 up 1 down 2 left 3 right 4 ok 5 close */
    if (ev->type == SDL_KEYDOWN && !ev->key.repeat) {
        if (ev->key.keysym.scancode == SDL_SCANCODE_F1) { toggle(); return; }
        if (!s_open) return;
        switch (ev->key.keysym.scancode) {
        case SDL_SCANCODE_UP: key = 0; break;
        case SDL_SCANCODE_DOWN: key = 1; break;
        case SDL_SCANCODE_LEFT: key = 2; break;
        case SDL_SCANCODE_RIGHT: key = 3; break;
        case SDL_SCANCODE_RETURN: case SDL_SCANCODE_Z: case SDL_SCANCODE_C: key = 4; break;
        case SDL_SCANCODE_ESCAPE: case SDL_SCANCODE_X: key = 5; break;
        default: break;
        }
    } else if (ev->type == SDL_KEYDOWN && ev->key.repeat && s_open) {
        if (ev->key.keysym.scancode == SDL_SCANCODE_UP) key = 0;
        if (ev->key.keysym.scancode == SDL_SCANCODE_DOWN) key = 1;
        if (ev->key.keysym.scancode == SDL_SCANCODE_LEFT) key = 2;
        if (ev->key.keysym.scancode == SDL_SCANCODE_RIGHT) key = 3;
    } else if (ev->type == SDL_CONTROLLERBUTTONDOWN) {
        if (ev->cbutton.button == SDL_CONTROLLER_BUTTON_BACK) { toggle(); return; }
        if (!s_open) return;
        switch (ev->cbutton.button) {
        case SDL_CONTROLLER_BUTTON_DPAD_UP: key = 0; break;
        case SDL_CONTROLLER_BUTTON_DPAD_DOWN: key = 1; break;
        case SDL_CONTROLLER_BUTTON_DPAD_LEFT: key = 2; break;
        case SDL_CONTROLLER_BUTTON_DPAD_RIGHT: key = 3; break;
        case SDL_CONTROLLER_BUTTON_A: case SDL_CONTROLLER_BUTTON_START: key = 4; break;
        case SDL_CONTROLLER_BUTTON_B: key = 5; break;
        default: break;
        }
    }
    switch (key) {
    case 0: s_sel = (s_sel + IT_COUNT - 1) % IT_COUNT; break;
    case 1: s_sel = (s_sel + 1) % IT_COUNT; break;
    case 2: activate(-1); break;
    case 3: activate(1); break;
    case 4: activate(0); break;
    case 5: s_open = 0; s_mute = 15; break;
    default: break;
    }
}

void DebugMenu_BeforeFrame(void)
{
    if (s_mute > 0) {           /* swallow the key that closed the menu (Enter = Start) */
        s_mute--;
        for (int p = 0; p < 2; p++) ((InputPort *)Input_GetPort(p))->raw = 0xFFFF;
    }
    if (s_msgT > 0) s_msgT--;
    if (!in_stage()) return;
    if (s_infHp && RS16(A_HP) > 0) W16(A_HP, R16(A_HP_MAX));
    if (s_infShur && RS16(A_SHURIKENS) < 99) W16(A_SHURIKENS, 99);
}

/* ------------------------------------------------------------------ drawing */

static void text(SDL_Renderer *r, int x, int y, const char *s)
{
    for (; *s; s++, x += 8) {
        int c = (unsigned char)*s;
        if (c >= 'a' && c <= 'z') c -= 32;
        if (c < 32 || c > 127) continue;
        for (int yy = 0; yy < 8; yy++) {
            unsigned char b = k_font8[c - 32][yy];
            for (int xx = 0; xx < 8; xx++)
                if (b & (0x80 >> xx)) SDL_RenderDrawPoint(r, x + xx, y + yy);
        }
    }
}

void DebugMenu_Draw(SDL_Renderer *r)
{
    if (!r) return;
    if (!s_open) {
        if (s_msgT > 0) {
            SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_BLEND);
            SDL_SetRenderDrawColor(r, 0, 0, 0, 170);
            SDL_Rect bg = { 8, 200, 8 * 20 + 8, 14 }; SDL_RenderFillRect(r, &bg);
            SDL_SetRenderDrawColor(r, 255, 230, 80, 255);
            text(r, 12, 203, s_msg);
        }
        return;
    }
    char b[64], sn[16];
    int st = in_stage();
    SDL_SetRenderDrawBlendMode(r, SDL_BLENDMODE_BLEND);
    SDL_SetRenderDrawColor(r, 0, 0, 0, 200);
    SDL_Rect bg = { 40, 24, 240, 176 }; SDL_RenderFillRect(r, &bg);
    SDL_SetRenderDrawColor(r, 255, 80, 80, 255);
    SDL_RenderDrawRect(r, &bg);
    text(r, 52, 32, "DEBUG / CHEATS");
    SDL_SetRenderDrawColor(r, 140, 140, 140, 255);
    text(r, 52, 44, "v" SL_VERSION);
    if (st) { stage_name(RS16(A_STAGE_IDX), sn); sprintf(b, "STAGE %s", sn); text(r, 196, 44, b); }
    else text(r, 196, 44, "HORS JEU");
    for (int i = 0; i < IT_COUNT; i++) {
        switch (i) {
        case IT_LIVES:    sprintf(b, "VIES           < %d >", RS16(A_LIVES)); break;
        case IT_REFILL:   sprintf(b, "ENERGIE        %d/%d", RS16(A_HP), RS16(A_HP_MAX)); break;
        case IT_INF_HP:   sprintf(b, "ENERGIE INFINIE  %s", s_infHp ? "ON" : "OFF"); break;
        case IT_SHUR:     sprintf(b, "SHURIKENS      < %d >", RS16(A_SHURIKENS)); break;
        case IT_INF_SHUR: sprintf(b, "SHURIKENS INF.   %s", s_infShur ? "ON" : "OFF"); break;
        case IT_NINJ:     sprintf(b, "NINJUTSU         %s", R16(A_NINJUTSU) ? "OUI" : "NON"); break;
        case IT_CLEAR:    sprintf(b, "FINIR LE STAGE"); break;
        case IT_GOTO:     stage_name(s_gotoIdx, sn); sprintf(b, "ALLER AU STAGE < %s >", sn); break;
        default:          sprintf(b, "FERMER"); break;
        }
        int y = 60 + i * 13;
        if (i == s_sel) {
            SDL_SetRenderDrawColor(r, 120, 30, 30, 255);
            SDL_Rect hl = { 46, y - 2, 228, 12 }; SDL_RenderFillRect(r, &hl);
            SDL_SetRenderDrawColor(r, 255, 255, 255, 255);
            text(r, 50, y, ">");
        } else SDL_SetRenderDrawColor(r, 200, 200, 200, 255);
        text(r, 60, y, b);
    }
    SDL_SetRenderDrawColor(r, 140, 140, 140, 255);
    text(r, 52, 184, s_msgT > 0 ? s_msg : "F1/BACK: FERMER");
}
