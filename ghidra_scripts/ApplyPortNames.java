// Applies docs/ghidra_names.csv (built by tools/mine_names.py from the PC port) to the
// current program: creates missing functions, renames FUN_/DAT_/LAB_ symbols and
// machine-generated handler names, adds a plate comment pointing at the port's C code.
// Human-typed names are kept (the port name is added as a secondary label).
// Re-runnable: the comment block between [port-sync] markers is replaced, not appended.
//
// Script args (key=value): csv=<docs/ghidra_names.csv> report=<out.tsv>
//   bss=1  also create an uninitialized "BSS" block from the end of the loaded image to
//          0x060FFFFF so labels on work-RAM globals past the image can be placed (default 0)
// Program role from its name: SHINOBI.dec* -> SHINOBI, DIRECTOR.dec* -> DIRECTOR,
// A.BIN* -> A.BIN; the A.BIN rows are also applied to the overlay programs, which carry
// A.BIN at 0x06004000-0x0603FFFF. Any other program (track1.iso, *.PPB) is skipped.
// @category ShinobiLegions
import ghidra.app.script.GhidraScript;
import ghidra.app.cmd.disassemble.DisassembleCommand;
import ghidra.app.cmd.function.CreateFunctionCmd;
import ghidra.program.model.address.*;
import ghidra.program.model.listing.*;
import ghidra.program.model.mem.*;
import ghidra.program.model.symbol.*;
import java.io.*;
import java.nio.file.*;
import java.util.*;
import java.util.regex.*;

public class ApplyPortNames extends GhidraScript {
    static final Pattern DEFAULT = Pattern.compile(
        "^(FUN|SUB|LAB|DAT|PTR|UNK|thunk_FUN|f|sub|switchD|caseD|BYTE|WORD|DWORD|s|u|ds)_[0-9A-Fa-f]{6,8}(_.*)?$");
    // names generated by ghidra_scripts/CreateMissingFunctions.java & co. (index-based, not semantic)
    static final Pattern GENERIC = Pattern.compile(
        "^(EnemyHandler|EnemyLoader|ProjHandler|ObjHandler10|ObjHandler|Handler|Proj|Obj)_(0x)?[0-9A-Fa-f]{1,4}$");
    static final String B = "[port-sync]", E = "[/port-sync]";

    Map<String, Integer> cnt = new TreeMap<>();
    PrintWriter rep;
    String role;

    void inc(String k) { cnt.merge(k, 1, Integer::sum); }

    static List<String> parseCsvLine(String l) {
        List<String> out = new ArrayList<>();
        StringBuilder sb = new StringBuilder();
        boolean q = false;
        for (int i = 0; i < l.length(); i++) {
            char c = l.charAt(i);
            if (q) {
                if (c == '"') {
                    if (i + 1 < l.length() && l.charAt(i + 1) == '"') { sb.append('"'); i++; }
                    else q = false;
                } else sb.append(c);
            } else if (c == '"') q = true;
            else if (c == ',') { out.add(sb.toString()); sb.setLength(0); }
            else sb.append(c);
        }
        out.add(sb.toString());
        return out;
    }

    void log(String addr, String kind, String name, String action, String old) {
        rep.println(currentProgram.getName() + "\t" + addr + "\t" + kind + "\t" + name + "\t" + action + "\t" + (old == null ? "" : old));
        String k = action.startsWith("kept") || action.startsWith("same") ? action.split(" \\(")[0] : action.split(":")[0];
        inc(kind + ":" + k);
    }

    boolean initialized(Address a) {
        MemoryBlock b = currentProgram.getMemory().getBlock(a);
        return b != null && b.isInitialized();
    }

    String setBlock(String old, String body) {
        String blk = B + "\n" + body + "\n" + E;
        if (old == null || old.isEmpty()) return blk;
        int i = old.indexOf(B), j = old.indexOf(E);
        if (i >= 0 && j > i) return old.substring(0, i) + blk + old.substring(j + E.length());
        return old + "\n" + blk;
    }

    void addSecondary(Address a, String name) throws Exception {
        SymbolTable st = currentProgram.getSymbolTable();
        for (Symbol s : st.getSymbols(a)) if (s.getName().equals(name)) return;
        st.createLabel(a, name, SourceType.IMPORTED);
    }

    // same name modulo case/underscores, or one extends the other (ObjHandler_1000 vs ObjHandler_1000_BreakableBox)
    static boolean compatible(String a, String b) {
        String x = a.replace("_", "").toLowerCase(), y = b.replace("_", "").toLowerCase();
        return x.equals(y) || x.startsWith(y) || x.endsWith(y) || y.startsWith(x) || y.endsWith(x);
    }

    boolean isCalled(Address a) {
        for (Reference r : getReferencesTo(a)) if (r.getReferenceType().isCall()) return true;
        return false;
    }

    String uniq(String name, Address a) {
        return name + "_" + a.toString().toUpperCase();
    }

    void doFunction(Address a, String addr, String name, String body) throws Exception {
        Function f = getFunctionAt(a);
        boolean created = false;
        if (f == null) {
            Function c = getFunctionContaining(a);
            if (c != null && isCalled(a) && getInstructionAt(a) != null) {
                // a real subroutine (bsr/jsr target) that analysis swallowed into its caller's body
                new CreateFunctionCmd(null, a, null, SourceType.IMPORTED, false, true).applyTo(currentProgram, monitor);
                f = getFunctionAt(a);
                if (f != null) { created = true; c = null; body = body + "\n(split out of " + getFunctionContaining(a.subtract(2)) + ")"; }
            }
            if (c != null) {
                if (!name.isEmpty()) addSecondary(a, name);
                Instruction ins = getInstructionAt(a);
                if (ins != null) setPreComment(a, setBlock(getPreComment(a), body));
                log(addr, "function", name, "inside:" + c.getName() + "@" + c.getEntryPoint(), null);
                return;
            }
        }
        if (f == null) {
            if (getInstructionAt(a) == null) {
                Data d = getDataContaining(a);
                if (d != null && d.isDefined()) {
                    if (!name.isEmpty()) addSecondary(a, name);
                    log(addr, "function", name, "notcode:defined data " + d.getDataType().getName(), null);
                    return;
                }
                new DisassembleCommand(a, null, true).applyTo(currentProgram, monitor);
            }
            if (getInstructionAt(a) != null) new CreateFunctionCmd(a).applyTo(currentProgram, monitor);
            f = getFunctionAt(a);
            if (f == null) {
                if (!name.isEmpty()) currentProgram.getSymbolTable().createLabel(a, name, SourceType.IMPORTED);
                log(addr, "function", name, "createfail", null);
                return;
            }
            created = true;
        }
        String cur = f.getName();
        SourceType cs = f.getSymbol().getSource();
        // IMPORTED = set by a previous run of this script -> may be updated; USER_DEFINED = human
        boolean curDefault = cs == SourceType.DEFAULT || cs == SourceType.IMPORTED || cs == SourceType.ANALYSIS || DEFAULT.matcher(cur).matches();
        boolean curGeneric = GENERIC.matcher(cur).matches();
        String action, old = cur;
        if (name.isEmpty()) action = created ? "created" : "commented";
        else if (cur.equals(name)) action = created ? "created" : "same";
        else if (curGeneric && GENERIC.matcher(name).matches()) { addSecondary(a, name); action = "same:both index-based (" + cur + ")"; }
        else if (!curDefault && compatible(cur, name)) { addSecondary(a, name); action = "same:compatible human name"; }
        else if (curDefault || (curGeneric && !GENERIC.matcher(name).matches())) {
            try { f.setName(name, SourceType.IMPORTED); }
            catch (ghidra.util.exception.DuplicateNameException ex) { f.setName(uniq(name, a), SourceType.IMPORTED); }
            action = created ? "created" : "renamed";
            if (curGeneric) body = body + "\nprevious name: " + cur;
        } else {
            addSecondary(a, name);
            action = "kept:differs";
            body = body + "\nport name: " + name;
        }
        setPlateComment(a, setBlock(getPlateComment(a), body));
        log(addr, "function", name, action, old);
    }

    void doData(Address a, String addr, String name, String body) throws Exception {
        SymbolTable st = currentProgram.getSymbolTable();
        Symbol s = st.getPrimarySymbol(a);
        String old = s == null ? null : s.getName();
        String action;
        if (s != null && s.getName().equals(name)) action = "same";
        else if (s == null || s.getSource() == SourceType.DEFAULT || s.getSource() == SourceType.IMPORTED
                 || s.getSource() == SourceType.ANALYSIS || DEFAULT.matcher(s.getName()).matches()) {
            Symbol n = null;
            for (Symbol x : st.getSymbols(a)) if (x.getName().equals(name)) n = x;
            if (n == null) n = st.createLabel(a, name, SourceType.IMPORTED);
            if (!n.isPrimary()) n.setPrimary();
            action = s == null ? "labeled" : "renamed";
        } else if (s.getSymbolType() == SymbolType.FUNCTION) {
            addSecondary(a, name);
            action = "kept:function here";
        } else {
            addSecondary(a, name);
            action = "kept";
        }
        String eol = getEOLComment(a);
        String line = "[port] " + body.replace('\n', ' ');
        if (eol != null) {
            StringBuilder sb = new StringBuilder();
            for (String l : eol.split("\n")) if (!l.startsWith("[port] ")) sb.append(sb.length() > 0 ? "\n" : "").append(l);
            eol = sb.length() > 0 ? sb + "\n" + line : line;
        } else eol = line;
        setEOLComment(a, eol);
        log(addr, "data", name, action, old);
    }

    void makeBss() throws Exception {
        Memory m = currentProgram.getMemory();
        long end = 0;
        for (MemoryBlock b : m.getBlocks()) {
            long s = b.getStart().getOffset(), e = b.getEnd().getOffset();
            if (s >= 0x06000000L && s < 0x06100000L && e > end) end = e;
        }
        if (end != 0 && end < 0x060FFFFFL) {
            Address s = toAddr(end + 1);
            m.createUninitializedBlock("BSS", s, 0x06100000L - (end + 1), false);
            println("created BSS block " + s + "-060fffff");
        }
        if (!m.contains(toAddr(0x06000000L)) && m.contains(toAddr(0x06004000L))) {
            m.createUninitializedBlock("WRAM_H_LOW", toAddr(0x06000000L), 0x4000, false);
            println("created BSS block WRAM_H_LOW 06000000-06003fff");
        }
    }

    public void run() throws Exception {
        Map<String, String> args = new HashMap<>();
        for (String s : getScriptArgs()) { int i = s.indexOf('='); if (i > 0) args.put(s.substring(0, i), s.substring(i + 1)); }
        String pn = currentProgram.getName();
        if (pn.startsWith("SHINOBI.dec")) role = "SHINOBI";
        else if (pn.startsWith("DIRECTOR.dec")) role = "DIRECTOR";
        else if (pn.startsWith("A.BIN")) role = "A.BIN";
        else { println("skip program " + pn); return; }
        if ("1".equals(args.get("bss"))) makeBss();
        rep = new PrintWriter(new FileWriter(args.get("report") + "." + role + ".tsv"));
        rep.println("program\taddress\tkind\tcsv_name\taction\tprevious");
        List<String> lines = Files.readAllLines(Paths.get(args.get("csv")));
        List<String> hdr = parseCsvLine(lines.get(0));
        int iP = hdr.indexOf("program"), iA = hdr.indexOf("address"), iK = hdr.indexOf("kind"),
            iN = hdr.indexOf("name"), iC = hdr.indexOf("comment"), iAl = hdr.indexOf("aliases"), iS = hdr.indexOf("source");
        for (String l : lines.subList(1, lines.size())) {
            if (l.trim().isEmpty()) continue;
            List<String> r = parseCsvLine(l);
            String prog = r.get(iP);
            if (!prog.equals(role) && !(prog.equals("A.BIN") && !role.equals("A.BIN"))) continue;
            String addr = r.get(iA), kind = r.get(iK), name = r.get(iN);
            Address a = toAddr(Long.parseLong(addr.replace("0x", ""), 16));
            if (!currentProgram.getMemory().contains(a)) { log(addr, kind, name, "nomem", null); continue; }
            if (kind.equals("function") && !initialized(a)) { log(addr, kind, name, "nomem", null); continue; }
            String body = r.get(iC) + "\nsource: " + r.get(iS);
            if (iAl >= 0 && !r.get(iAl).isEmpty()) body += "\nother port names: " + r.get(iAl).replace("|", ", ");
            try {
                if (kind.equals("function")) doFunction(a, addr, name, body);
                else doData(a, addr, name, body);
            } catch (Exception ex) {
                log(addr, kind, name, "error:" + ex.getMessage(), null);
            }
        }
        rep.close();
        StringBuilder sb = new StringBuilder("SUMMARY " + pn + " role=" + role);
        for (var e : cnt.entrySet()) sb.append(" ").append(e.getKey()).append("=").append(e.getValue());
        println(sb.toString());
    }
}
